# usage: python3 -I build_drills.py <hoverDir> <out.js>
# Runs each reference solution to compute expected outputs, checks them through the real harness, writes window.DRILLS.
import sys, json, copy, os
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
sys.path.insert(0, sys.argv[1])
import drills_src, harness
out, bad = [], 0
for d in drills_src.DRILLS:
    ns = {}
    exec(compile(d['sol'], d['id'] + '_sol.py', 'exec'), ns)
    fn = ns[d['fn']]
    tests = []
    for t in d['tests']:
        exp = fn(*copy.deepcopy(t['args']))
        json.dumps(exp)
        tt = {'args': t['args'], 'expect': exp}
        if t.get('hidden'): tt['hidden'] = True
        if t.get('why'): tt['why'] = t['why']
        if d.get('tol'): tt['tol'] = d['tol']
        tests.append(tt)
    spec = {'fn': d['fn'], 'tests': tests}
    r = json.loads(harness.run(d['sol'], json.dumps({'drill': spec})))
    if not r['passed']:
        bad += 1; print('REFERENCE FAILS', d['id'], [x for x in r['tests'] if not x['ok']], r.get('error'))
    r0 = json.loads(harness.run(d['start'], json.dumps({'drill': spec})))
    if r0['passed'] or r0.get('error'):
        bad += 1; print('STARTER PROBLEM', d['id'], r0['score'], r0.get('error'))
    exps = [json.dumps(t['expect']) for t in tests]
    print(d['id'].ljust(9), 'L%d' % d['lvl'], 'ref', r['score'], 'starter', r0['score'], '|', ' ; '.join(e if len(e) < 40 else e[:37] + '...' for e in exps))
    o = {k: d[k] for k in ('id', 'lvl', 'topic', 't', 'fn', 'mins', 'prompt', 'start', 'sol', 'hint', 'talk')}
    o['tests'] = tests
    out.append(o)
if bad:
    print('FAILURES', bad); sys.exit(1)
open(sys.argv[2], 'w', encoding='utf-8').write('/* SUMMIT · interview drills (generated by scripts/build_drills.py; edit scripts/drills_src.py) */\nwindow.DRILLS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('wrote', sys.argv[2], len(out), 'drills')
